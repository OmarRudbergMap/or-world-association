-- =====================================================================
--  O.R. WORLD ASSOCIATION
--  LE PASSEPORT ET LES COMPTEURS DE L'ESPACE MEMBRE
--  ---------------------------------------------------------------
--  Jusqu'ici le passeport se remplissait tout seul : on cliquait un
--  tampon et il restait dans le navigateur. Les compteurs de l'espace
--  membre, eux, etaient ecrits a la main a zero.
--
--  Ce fichier cree ce qui manquait, puis donne deux fonctions que le
--  site appelle : l'une rend les tampons gagnes, l'autre les six
--  chiffres de « Ma participation ». Tout est calcule depuis les
--  vraies tables, pour le membre connecte et lui seul.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. LES PARTICIPATIONS
--    Une ligne par participation : un message pour l'anniversaire, un
--    envoi aux radios, un atelier, un jeu concours, un projet.
-- ---------------------------------------------------------------------
create table if not exists asso_participations (
  id       bigint generated by default as identity primary key,
  membre   uuid not null references auth.users(id) on delete cascade,
  action   text not null check (action in
             ('message','radio','anniversaire','atelier','concours',
              'projet','secret')),
  detail   text,
  le_jour  date not null default current_date,
  statut   text not null default 'valide'
           check (statut in ('en attente','valide','refuse')),
  cree_le  timestamptz not null default now()
);

create index if not exists asso_participations_idx
  on asso_participations (membre, action);

alter table asso_participations enable row level security;

drop policy if exists "participations lecture"  on asso_participations;
drop policy if exists "participations ecriture" on asso_participations;

create policy "participations lecture" on asso_participations
  for select to authenticated using (membre = auth.uid());

create policy "participations ecriture" on asso_participations
  for insert to authenticated with check (membre = auth.uid());


-- ---------------------------------------------------------------------
-- 2. LES COMMANDES
--    La boutique est en preparation. La table existe pour que le
--    compteur dise un vrai zero, et se remplisse le jour de l'ouverture.
-- ---------------------------------------------------------------------
create table if not exists asso_commandes (
  id       bigint generated by default as identity primary key,
  membre   uuid references auth.users(id) on delete set null,
  email    text,
  numero   text,
  somme    numeric(10,2),
  le_jour  date not null default current_date,
  statut   text not null default 'payee',
  cree_le  timestamptz not null default now()
);

create index if not exists asso_commandes_idx on asso_commandes (membre);

alter table asso_commandes enable row level security;

drop policy if exists "commandes lecture" on asso_commandes;

create policy "commandes lecture" on asso_commandes
  for select to authenticated using (membre = auth.uid());


-- ---------------------------------------------------------------------
-- 2 bis. LES DOCUMENTS DU MEMBRE
--    Une ligne par piece : l'autorisation de droit a l'image, le
--    reglement interieur signe, une facture. Le bureau les depose,
--    le membre les retrouve dans son espace.
-- ---------------------------------------------------------------------
create table if not exists asso_documents (
  id       bigint generated by default as identity primary key,
  membre   uuid not null references auth.users(id) on delete cascade,
  titre    text not null,
  detail   text,
  lien     text,
  statut   text not null default 'recu'
           check (statut in ('recu','attente')),
  le_jour  date not null default current_date,
  cree_le  timestamptz not null default now()
);

create index if not exists asso_documents_idx on asso_documents (membre);

alter table asso_documents enable row level security;

drop policy if exists "documents lecture" on asso_documents;

create policy "documents lecture" on asso_documents
  for select to authenticated using (membre = auth.uid());


-- ---------------------------------------------------------------------
-- 3. LES TAMPONS DU PASSEPORT
--    Rend un objet : un tampon par cle, vrai si le membre l'a gagne.
-- ---------------------------------------------------------------------
create or replace function asso_mon_passeport()
returns jsonb
language sql
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'first',    exists (select 1 from asso_adhesions a
                         where a.membre = auth.uid()),
    'book',     exists (select 1 from asso_histoires h
                         where h.membre = auth.uid()),
    'vote',     exists (select 1 from asso_votes_chansons v
                         where v.user_id = auth.uid()),
    'crew',     exists (select 1 from asso_recits r
                         where r.membre = auth.uid()),
    'shop',     exists (select 1 from asso_commandes c
                         where c.membre = auth.uid()),
    'radio',    exists (select 1 from asso_participations p
                         where p.membre = auth.uid()
                           and p.action = 'radio' and p.statut = 'valide'),
    'message',  exists (select 1 from asso_participations p
                         where p.membre = auth.uid()
                           and p.action = 'message' and p.statut = 'valide'),
    'birthday', exists (select 1 from asso_participations p
                         where p.membre = auth.uid()
                           and p.action = 'anniversaire' and p.statut = 'valide'),
    'secret',   exists (select 1 from asso_participations p
                         where p.membre = auth.uid()
                           and p.action = 'secret'),
    'fm1',      exists (select 1 from asso_videos v
                         where v.user_id = auth.uid() and v.chapitre = 1),
    'fm2',      exists (select 1 from asso_videos v
                         where v.user_id = auth.uid() and v.chapitre = 2),
    'fm3',      exists (select 1 from asso_videos v
                         where v.user_id = auth.uid() and v.chapitre = 3),
    'fm4',      exists (select 1 from asso_videos v
                         where v.user_id = auth.uid() and v.chapitre = 4),
    'fmfull',   exists (select 1 from asso_videos v
                         where v.user_id = auth.uid() and v.chapitre = 5),

    -- les deux badges que la base sait decerner toute seule
    'b_ambassadeur', exists (select 1 from asso_ambassadeurs b
                              where b.user_id = auth.uid()),
    'b_cent',        exists (select 1 from asso_adhesions a
                              where a.membre = auth.uid()
                                and a.numero_membre is not null
                                and a.numero_membre <= 100)
  );
$$;

grant execute on function asso_mon_passeport() to authenticated;


-- ---------------------------------------------------------------------
-- 4. LES SIX CHIFFRES DE « MA PARTICIPATION »
-- ---------------------------------------------------------------------
create or replace function asso_ma_participation()
returns jsonb
language sql
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'concours',  (select count(*)::int from asso_participations p
                   where p.membre = auth.uid() and p.action = 'concours'),
    'votes',     (select count(*)::int from asso_votes_chansons v
                   where v.user_id = auth.uid()),
    'projets',   (select count(*)::int from asso_participations p
                   where p.membre = auth.uid() and p.action = 'projet'),
    'jours',     (select greatest(0, (current_date - min(a.date_debut)))::int
                   from asso_adhesions a where a.membre = auth.uid()),
    'ateliers',  (select count(*)::int from asso_participations p
                   where p.membre = auth.uid() and p.action = 'atelier'),
    'commandes', (select count(*)::int from asso_commandes c
                   where c.membre = auth.uid())
  );
$$;

grant execute on function asso_ma_participation() to authenticated;


-- ---------------------------------------------------------------------
-- 5. CE QUE LE BUREAU VOIT
--    La liste des participations en attente de validation.
-- ---------------------------------------------------------------------
create or replace view asso_participations_a_valider as
select p.id, p.membre, p.action, p.detail, p.le_jour, p.cree_le
  from asso_participations p
 where p.statut = 'en attente'
 order by p.cree_le;


-- ---------------------------------------------------------------------
-- 6. VERIFICATION
-- ---------------------------------------------------------------------
select 'participations' as table_creee, count(*) from asso_participations
union all
select 'commandes', count(*) from asso_commandes;
