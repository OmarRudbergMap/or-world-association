-- =====================================================================
--  O.R. WORLD ASSOCIATION
--  LES PAIEMENTS PAYPAL
--  ---------------------------------------------------------------
--  Meme principe que Stripe : toutes les cinq minutes, Supabase va
--  voir chez PayPal les paiements recus, et pour chacun qu'il ne
--  connait pas encore il cree l'adhesion ou le don, lui donne son
--  numero de recu dans la suite, et envoie le recu par mail.
--
--  Une difference : PayPal demande d'abord un jeton d'acces, qui
--  vaut une poignee d'heures. Il y a donc trois temps au lieu de
--  deux, mais la tache les enchaine toute seule.
--
--  A executer APRES asso_paiements_stripe.sql et asso_paiements_stripe_v2.sql,
--  et APRES avoir range les identifiants PayPal dans le coffre.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. CE QUI MANQUE DANS LES TABLES
-- ---------------------------------------------------------------------
alter table asso_adhesions add column if not exists paypal_id text;
alter table asso_dons      add column if not exists paypal_id text;

create unique index if not exists asso_adhesions_paypal
  on asso_adhesions (paypal_id) where paypal_id is not null;
create unique index if not exists asso_dons_paypal
  on asso_dons (paypal_id) where paypal_id is not null;


-- le jeton d'acces, garde au chaud tant qu'il est valable
create table if not exists asso_paypal_jeton (
  id        int primary key default 1,
  jeton     text,
  expire_le timestamptz,
  check (id = 1)
);
alter table asso_paypal_jeton enable row level security;


-- le suivi des questions posees a PayPal
create table if not exists asso_paypal_requete (
  id         bigint generated by default as identity primary key,
  etape      text not null,            -- 'jeton' ou 'transactions'
  demande    bigint not null,
  lancee_le  timestamptz not null default now(),
  traitee_le timestamptz
);
alter table asso_paypal_requete enable row level security;

create index if not exists asso_paypal_requete_attente
  on asso_paypal_requete (lancee_le) where traitee_le is null;


-- ---------------------------------------------------------------------
-- 2. POSER LA QUESTION A PAYPAL
--    S'il n'y a pas de jeton valable, on demande d'abord le jeton.
--    Sinon on demande directement la liste des paiements.
-- ---------------------------------------------------------------------
create or replace function asso_paypal_demander()
returns text
language plpgsql
security definer
set search_path = public, extensions, vault
as $$
declare
  v_id      text;
  v_secret  text;
  v_jeton   text;
  v_entete  jsonb;
  v_base    text;
  v_debut   text;
  v_fin     text;
  d         bigint;
begin
  -- une question est deja en attente : on ne double pas
  if exists (select 1 from asso_paypal_requete
              where traitee_le is null
                and lancee_le > now() - interval '20 minutes') then
    return 'une question est deja en attente';
  end if;

  select decrypted_secret into v_id
    from vault.decrypted_secrets where name = 'paypal_client_id';
  select decrypted_secret into v_secret
    from vault.decrypted_secrets where name = 'paypal_secret';
  if v_id is null or v_secret is null then
    raise exception 'Les identifiants PayPal sont absents du coffre '
                    '(noms attendus : paypal_client_id et paypal_secret)';
  end if;

  select j.jeton into v_jeton
    from asso_paypal_jeton j
   where j.id = 1 and j.expire_le > now() + interval '5 minutes';

  -- ----- premier temps : le jeton d'acces -----
  if v_jeton is null then
    -- l'encodage base64 de Postgres coupe les longues lignes : on recolle
    v_base := replace(
                encode(convert_to(v_id || ':' || v_secret, 'UTF8'), 'base64'),
                E'\n', '');
    v_entete := jsonb_build_object(
                  'Authorization', 'Basic ' || v_base,
                  'Content-Type',  'application/x-www-form-urlencoded',
                  'Accept',        'application/json');

    -- selon la version de pg_net, le corps se passe en texte ou non :
    -- on essaie la premiere forme, et on se rabat sur la seconde
    begin
      execute 'select net.http_post(url := $1, body := $2, headers := $3, '
              'timeout_milliseconds := 15000)'
        into d
        using 'https://api-m.paypal.com/v1/oauth2/token',
              'grant_type=client_credentials'::text,
              v_entete;
    exception when others then
      execute 'select net.http_post(url := $1, params := $2, body := ''{}''::jsonb, '
              'headers := $3, timeout_milliseconds := 15000)'
        into d
        using 'https://api-m.paypal.com/v1/oauth2/token',
              jsonb_build_object('grant_type', 'client_credentials'),
              v_entete;
    end;

    insert into asso_paypal_requete (etape, demande) values ('jeton', d);
    return 'jeton demande';
  end if;

  -- ----- deuxieme temps : les paiements des trente derniers jours -----
  v_debut := to_char((now() at time zone 'UTC') - interval '30 days',
                     'YYYY-MM-DD"T"HH24:MI:SS') || '-0000';
  v_fin   := to_char((now() at time zone 'UTC'),
                     'YYYY-MM-DD"T"HH24:MI:SS') || '-0000';

  select net.http_get(
      url := 'https://api-m.paypal.com/v1/reporting/transactions'
             || '?start_date=' || v_debut
             || '&end_date='   || v_fin
             || '&fields=transaction_info,payer_info'
             || '&page_size=100&page=1',
      headers := jsonb_build_object('Authorization', 'Bearer ' || v_jeton,
                                    'Accept', 'application/json'),
      timeout_milliseconds := 20000)
    into d;

  insert into asso_paypal_requete (etape, demande) values ('transactions', d);
  return 'paiements demandes';
end;
$$;


-- ---------------------------------------------------------------------
-- 3. LIRE LA REPONSE
-- ---------------------------------------------------------------------
create or replace function asso_paypal_traiter()
returns table (operation text, genre text, montant numeric, email text, resultat text)
language plpgsql
security definer
set search_path = public, extensions, vault
as $$
declare
  req     record;
  brut    text;
  code    int;
  rep     jsonb;
  item    jsonb;
  info    jsonb;
  payeur  jsonb;
  v_ref   text;
  v_email text;
  v_prenom text;
  v_nom   text;
  v_pays  text;
  v_lang  text;
  v_mont  numeric;
  v_objet text;
  v_genre text;
  v_num   text;
  v_debut date;
  v_fin   date;
begin
  select * into req
    from asso_paypal_requete
   where traitee_le is null
   order by lancee_le
   limit 1;
  if not found then return; end if;

  select r.status_code, r.content into code, brut
    from net._http_response r where r.id = req.demande;

  -- pas encore de reponse : on repassera au prochain tour
  if code is null then
    if req.lancee_le < now() - interval '30 minutes' then
      update asso_paypal_requete set traitee_le = now() where id = req.id;
      insert into asso_stripe_journal (resultat)
      values ('aucune reponse de PayPal (' || req.etape || ')');
    end if;
    return;
  end if;

  update asso_paypal_requete set traitee_le = now() where id = req.id;

  if code not between 200 and 299 then
    insert into asso_stripe_journal (resultat)
    values ('PayPal a repondu ' || code || ' (' || req.etape || ') : '
            || left(coalesce(brut, ''), 300));
    -- un jeton refuse est un jeton a refaire
    if req.etape = 'transactions' then
      delete from asso_paypal_jeton where id = 1;
    end if;
    return;
  end if;

  rep := brut::jsonb;

  -- ----- la reponse au jeton -----
  if req.etape = 'jeton' then
    insert into asso_paypal_jeton (id, jeton, expire_le)
    values (1, rep->>'access_token',
            now() + make_interval(secs => coalesce((rep->>'expires_in')::int, 28800)))
    on conflict (id) do update
       set jeton = excluded.jeton, expire_le = excluded.expire_le;
    insert into asso_stripe_journal (resultat) values ('jeton PayPal renouvele');
    return;
  end if;

  -- ----- la reponse aux paiements -----
  for item in select * from jsonb_array_elements(coalesce(rep->'transaction_details', '[]'::jsonb))
  loop
    info   := item->'transaction_info';
    payeur := item->'payer_info';
    v_ref  := info->>'transaction_id';

    continue when v_ref is null;
    continue when coalesce(info->>'transaction_status', '') <> 'S';

    v_mont := coalesce((info->'transaction_amount'->>'value')::numeric, 0);
    continue when v_mont <= 0;   -- remboursements, retraits, frais

    continue when exists (select 1 from asso_adhesions where paypal_id = v_ref)
               or exists (select 1 from asso_dons      where paypal_id = v_ref);

    v_email  := payeur->>'email_address';
    v_prenom := payeur->'payer_name'->>'given_name';
    v_nom    := payeur->'payer_name'->>'surname';
    if v_prenom is null and v_nom is null then
      v_prenom := split_part(coalesce(payeur->'payer_name'->>'alternate_full_name', ''), ' ', 1);
    end if;
    v_pays   := payeur->>'country_code';

    -- adhesion ou don ? ce que dit le libelle, sinon le montant
    v_objet := lower(coalesce(info->>'transaction_subject', '')
                     || ' ' || coalesce(info->>'transaction_note', '')
                     || ' ' || coalesce(info->>'invoice_id', ''));
    if v_objet like '%adhes%' or v_objet like '%member%' or v_objet like '%cotis%' then
      v_genre := 'adhesion';
    elsif v_objet like '%don%' or v_objet like '%donat%' then
      v_genre := 'don';
    elsif v_mont = 12 then
      v_genre := 'adhesion';
    else
      v_genre := 'don';
    end if;

    v_lang := case upper(coalesce(v_pays, ''))
                when 'FR' then 'fr' when 'BE' then 'fr' when 'CA' then 'fr'
                when 'ES' then 'es' when 'SE' then 'sv'
                when 'DE' then 'de' when 'AT' then 'de' when 'CH' then 'de'
                when 'PT' then 'pt' when 'BR' then 'pt'
                else 'en' end;

    -- la vraie date du paiement, pas celle du jour ou on le decouvre
    v_debut := coalesce((info->>'transaction_initiation_date')::timestamptz::date,
                        current_date);

    if v_genre = 'adhesion' then
      v_fin := (v_debut + interval '1 year' - interval '1 day')::date;
      v_num := asso_prochain_recu('ADH', extract(year from v_debut)::int);
      insert into asso_adhesions
        (email, prenom, nom, pays, langue, date_debut, date_fin, montant,
         moyen, numero_recu, origine, annee, paypal_id, statut, recu_envoye)
      values
        (v_email, v_prenom, v_nom, v_pays, v_lang, v_debut, v_fin, v_mont,
         'paypal', v_num, 'paypal', extract(year from v_debut)::int, v_ref, 'actif',
         case when asso_envoyer_recu('recu_adhesion', v_email, v_lang, v_num, v_mont, v_debut, v_fin)
              then now() else null end);
      resultat := 'adhesion creee';
    else
      v_num := asso_prochain_recu('DON', extract(year from v_debut)::int);
      insert into asso_dons
        (email, prenom, nom, pays, langue, montant, moyen, numero_recu,
         fait_le, paypal_id, statut, recu_envoye)
      values
        (v_email, v_prenom, v_nom, v_pays, v_lang, v_mont, 'paypal', v_num,
         v_debut, v_ref, 'valide',
         case when asso_envoyer_recu('recu_don', v_email, v_lang, v_num, v_mont, v_debut, null)
              then now() else null end);
      resultat := 'don enregistre';
    end if;

    insert into asso_stripe_journal (session, genre, montant, email, resultat)
    values (v_ref, v_genre, v_mont, v_email, 'paypal : ' || resultat);

    operation := v_ref; genre := v_genre; montant := v_mont; email := v_email;
    return next;
  end loop;
end;
$$;

revoke all on function asso_paypal_demander() from anon, authenticated;
revoke all on function asso_paypal_traiter()  from anon, authenticated;


-- ---------------------------------------------------------------------
-- 4. LA TACHE, TOUTES LES CINQ MINUTES
-- ---------------------------------------------------------------------
do $t$
begin
  perform cron.unschedule('paiements-paypal');
exception when others then null;
end $t$;

select cron.schedule('paiements-paypal', '*/5 * * * *',
                     $job$ select asso_paypal_traiter(); select asso_paypal_demander(); $job$);


