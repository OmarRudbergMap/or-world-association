-- =====================================================================
--  O.R. WORLD ASSOCIATION
--  LES CONTRIBUTIONS DES VISITEURS
--  ---------------------------------------------------------------
--  Deux formulaires du site existaient mais n'enregistraient rien :
--    « Vous y etiez ? »            sur la page des concerts
--    « Vous avez trouve un article ? » sur la page de la presse
--
--  Ce script cree les deux tables qui les recoivent. Tout arrive en
--  attente de relecture : rien ne s'affiche sur le site sans que vous
--  l'ayez valide.
--  Relancable autant de fois qu'on veut.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. LES RECITS DE CONCERT
-- ---------------------------------------------------------------------
create table if not exists asso_recits (
  id        bigint generated by default as identity primary key,
  membre    uuid references auth.users(id) on delete set null,
  signature text not null,                 -- « Camille, France »
  concert   text not null,                 -- « Paris, 03/11/2025 »
  recit     text not null,
  langue    text,
  statut    text not null default 'en attente',
  cree_le   timestamptz not null default now(),
  constraint asso_recits_taille check (
    char_length(signature) between 2 and 120 and
    char_length(concert)   between 2 and 120 and
    char_length(recit)     between 20 and 4000)
);

alter table asso_recits enable row level security;

drop policy if exists "envoyer un recit"   on asso_recits;
drop policy if exists "relire son recit"   on asso_recits;

-- tout le monde peut envoyer, mais seulement en attente de relecture
create policy "envoyer un recit" on asso_recits
  for insert to anon, authenticated
  with check (statut = 'en attente');

-- un membre connecte peut relire ce qu'il a envoye
create policy "relire son recit" on asso_recits
  for select to authenticated
  using (membre = auth.uid());


-- ---------------------------------------------------------------------
-- 2. LES ARTICLES DE PRESSE SIGNALES PAR LES VISITEURS
--    Attention : asso_articles existe deja, c'est la table du blog.
--    Celle-ci porte donc un autre nom.
-- ---------------------------------------------------------------------
create table if not exists asso_presse_signalee (
  id            bigint generated by default as identity primary key,
  membre        uuid references auth.users(id) on delete set null,
  media         text not null,             -- « Vogue Scandinavia, Suede »
  date_parution text,
  lien          text not null,
  langue        text,
  statut        text not null default 'en attente',
  cree_le       timestamptz not null default now(),
  constraint asso_presse_taille check (
    char_length(media) between 2 and 160 and
    char_length(lien)  between 8 and 500),
  constraint asso_presse_lien check (lien ~* '^https?://')
);

alter table asso_presse_signalee enable row level security;

drop policy if exists "signaler un article" on asso_presse_signalee;
drop policy if exists "relire son article"  on asso_presse_signalee;

create policy "signaler un article" on asso_presse_signalee
  for insert to anon, authenticated
  with check (statut = 'en attente');

create policy "relire son article" on asso_presse_signalee
  for select to authenticated
  using (membre = auth.uid());


-- ---------------------------------------------------------------------
-- 3. VOTRE PAGE DE RELECTURE
--    Tout ce qui attend votre feu vert, au meme endroit.
--    Pour valider : update asso_recits set statut = 'publie' where id = ...
--    Pour ecarter : update asso_recits set statut = 'ecarte' where id = ...
-- ---------------------------------------------------------------------
create or replace view asso_a_relire as
  select 'récit de concert' as nature, id, cree_le,
         signature          as qui,
         concert            as objet,
         left(recit, 400)   as contenu,
         langue, statut
    from asso_recits
   where statut = 'en attente'
  union all
  select 'article de presse', id, cree_le,
         coalesce(media, '') as qui,
         coalesce(date_parution, '') as objet,
         lien,
         langue, statut
    from asso_presse_signalee
   where statut = 'en attente'
   order by cree_le desc;

revoke all on asso_a_relire from anon, authenticated;


-- ---------------------------------------------------------------------
-- 4. VERIFICATION
-- ---------------------------------------------------------------------
select 'asso_recits'   as table_, count(*) as lignes from asso_recits
union all
select 'asso_presse_signalee',        count(*) from asso_presse_signalee;
