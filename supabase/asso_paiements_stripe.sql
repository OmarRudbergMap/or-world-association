-- ---------------------------------------------------------------------
-- 2. LA NUMEROTATION DES RECUS
--    Suite continue, sans trou, une par annee et par genre.
--    ADH-2026-011, puis 012, et ainsi de suite. DON-2026-001 pour les dons.
-- ---------------------------------------------------------------------
create or replace function asso_prochain_recu(prefixe text, an int)
returns text
language plpgsql
as $$
declare n int;
begin
  -- deux paiements simultanes ne peuvent pas recevoir le meme numero
  perform pg_advisory_xact_lock(hashtext(prefixe || an::text));
  if prefixe = 'DON' then
    select coalesce(max(substring(numero_recu from '[0-9]+$')::int), 0) + 1 into n
      from asso_dons
     where numero_recu like prefixe || '-' || an::text || '-%';
  else
    select coalesce(max(substring(numero_recu from '[0-9]+$')::int), 0) + 1 into n
      from asso_adhesions
     where numero_recu like prefixe || '-' || an::text || '-%';
  end if;
  return prefixe || '-' || an::text || '-' || lpad(n::text, 3, '0');
end;
$$;


