-- =====================================================================
--  O.R. WORLD ASSOCIATION
--  CORRECTIF : LA LECTURE DES PAIEMENTS STRIPE EN DEUX TEMPS
--  ---------------------------------------------------------------
--  Pourquoi : pg_net n'envoie la requete qu'une fois la transaction
--  terminee. Une fonction ne peut donc pas poser la question a Stripe
--  et attendre la reponse dans le meme mouvement. On separe :
--    asso_stripe_demander()  pose la question
--    asso_stripe_traiter()   lit la reponse et enregistre les paiements
--  La tache fait les deux a la suite, toutes les cinq minutes : elle
--  traite la reponse du passage precedent, puis repose la question.
--
--  A executer APRES asso_paiements_stripe.sql.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. LE SUIVI DES DEMANDES
-- ---------------------------------------------------------------------
create table if not exists asso_stripe_requete (
  id         bigint generated by default as identity primary key,
  demande    bigint not null,
  lancee_le  timestamptz not null default now(),
  traitee_le timestamptz
);

alter table asso_stripe_requete enable row level security;

create index if not exists asso_stripe_requete_attente
  on asso_stripe_requete (lancee_le) where traitee_le is null;


-- ---------------------------------------------------------------------
-- 2. POSER LA QUESTION A STRIPE
-- ---------------------------------------------------------------------
create or replace function asso_stripe_demander()
returns bigint
language plpgsql
security definer
set search_path = public, extensions, vault
as $$
declare cle_api text; d bigint;
begin
  select decrypted_secret into cle_api
    from vault.decrypted_secrets where name = 'stripe_api_key';
  if cle_api is null then
    raise exception 'La cle Stripe est absente du coffre (nom attendu : stripe_api_key)';
  end if;

  select net.http_get(
      url     := 'https://api.stripe.com/v1/checkout/sessions?limit=25&expand%5B%5D=data.line_items',
      headers := jsonb_build_object('Authorization', 'Bearer ' || cle_api),
      timeout_milliseconds := 15000)
    into d;

  insert into asso_stripe_requete (demande) values (d);
  return d;
end;
$$;


-- ---------------------------------------------------------------------
-- 3. LIRE LA REPONSE ET ENREGISTRER LES PAIEMENTS
-- ---------------------------------------------------------------------
create or replace function asso_stripe_traiter()
returns table (session text, genre text, montant numeric, email text, resultat text)
language plpgsql
security definer
set search_path = public, extensions, vault
as $$
declare
  req     record;
  rep     jsonb;
  brut    text;
  code    int;
  item    jsonb;
  ligne   jsonb;
  v_sess  text;
  v_email text;
  v_nom   text;
  v_pays  text;
  v_lang  text;
  v_mont  numeric;
  v_prod  text;
  v_genre text;
  v_num   text;
  v_debut date;
  v_fin   date;
begin
  -- la plus ancienne demande qui n'a pas encore ete traitee
  select * into req
    from asso_stripe_requete
   where traitee_le is null
   order by lancee_le
   limit 1;
  if not found then return; end if;

  select r.status_code, r.content into code, brut
    from net._http_response r where r.id = req.demande;

  -- pas encore de reponse : on repassera au prochain tour
  if code is null then
    -- sauf si la demande est vieille, auquel cas elle est perdue
    if req.lancee_le < now() - interval '30 minutes' then
      update asso_stripe_requete set traitee_le = now() where id = req.id;
      insert into asso_stripe_journal (resultat) values ('aucune reponse de Stripe');
    end if;
    return;
  end if;

  update asso_stripe_requete set traitee_le = now() where id = req.id;

  if code <> 200 then
    insert into asso_stripe_journal (resultat)
    values ('Stripe a repondu ' || code || ' : ' || left(coalesce(brut, ''), 300));
    return;
  end if;

  rep := brut::jsonb;

  for item in select * from jsonb_array_elements(rep->'data')
  loop
    v_sess := item->>'id';
    continue when coalesce(item->>'payment_status','') <> 'paid';
    continue when exists (select 1 from asso_adhesions where stripe_session = v_sess)
               or exists (select 1 from asso_dons      where stripe_session = v_sess);

    v_email := coalesce(item->'customer_details'->>'email', item->>'customer_email');
    v_nom   := item->'customer_details'->>'name';
    v_pays  := item->'customer_details'->'address'->>'country';
    v_mont  := coalesce((item->>'amount_total')::numeric, 0) / 100.0;

    ligne   := item->'line_items'->'data'->0;
    v_prod  := coalesce(ligne->>'description', '');
    select p.genre into v_genre from asso_stripe_produits p where p.nom = v_prod;
    if v_genre is null then
      v_genre := case when v_mont = 12 then 'adhesion' else 'don' end;
    end if;

    v_lang := case upper(coalesce(v_pays,''))
                when 'FR' then 'fr' when 'BE' then 'fr' when 'CA' then 'fr'
                when 'ES' then 'es' when 'SE' then 'sv'
                when 'DE' then 'de' when 'AT' then 'de' when 'CH' then 'de'
                when 'PT' then 'pt' when 'BR' then 'pt'
                else 'en' end;

    if v_genre = 'adhesion' then
      v_debut := current_date;
      v_fin   := (current_date + interval '1 year' - interval '1 day')::date;
      v_num   := asso_prochain_recu('ADH', extract(year from v_debut)::int);
      insert into asso_adhesions
        (email, prenom, nom, pays, langue, date_debut, date_fin, montant,
         moyen, numero_recu, origine, annee, stripe_session, recu_envoye)
      values
        (v_email, split_part(coalesce(v_nom,''), ' ', 1),
         nullif(trim(substring(coalesce(v_nom,'') from position(' ' in coalesce(v_nom,' ')))), ''),
         v_pays, v_lang, v_debut, v_fin, v_mont,
         'stripe', v_num, 'stripe', extract(year from v_debut)::int, v_sess,
         case when asso_envoyer_recu('recu_adhesion', v_email, v_lang, v_num, v_mont, v_debut, v_fin)
              then now() else null end);
      resultat := 'adhesion creee';
    else
      v_debut := current_date;
      v_num   := asso_prochain_recu('DON', extract(year from v_debut)::int);
      insert into asso_dons
        (email, prenom, nom, pays, langue, montant, moyen, numero_recu,
         stripe_session, recu_envoye)
      values
        (v_email, split_part(coalesce(v_nom,''), ' ', 1),
         nullif(trim(substring(coalesce(v_nom,'') from position(' ' in coalesce(v_nom,' ')))), ''),
         v_pays, v_lang, v_mont, 'stripe', v_num, v_sess,
         case when asso_envoyer_recu('recu_don', v_email, v_lang, v_num, v_mont, v_debut, null)
              then now() else null end);
      resultat := 'don enregistre';
    end if;

    insert into asso_stripe_journal (session, genre, montant, email, resultat)
    values (v_sess, v_genre, v_mont, v_email, resultat);

    session := v_sess; genre := v_genre; montant := v_mont; email := v_email;
    return next;
  end loop;

  update asso_adhesions a
     set membre = u.id
    from auth.users u
   where a.membre is null and a.email is not null
     and lower(a.email) = lower(u.email);
end;
$$;

revoke all on function asso_stripe_demander() from anon, authenticated;
revoke all on function asso_stripe_traiter()  from anon, authenticated;

-- l'ancienne fonction, celle qui attendait pour rien
drop function if exists asso_lire_stripe();


-- ---------------------------------------------------------------------
-- 4. LA TACHE : traiter la reponse d'avant, puis reposer la question
-- ---------------------------------------------------------------------
do $$
begin
  perform cron.unschedule('paiements-stripe');
exception when others then null;
end $$;

select cron.schedule('paiements-stripe', '*/5 * * * *',
                     $job$ select asso_stripe_traiter(); select asso_stripe_demander(); $job$);


-- ---------------------------------------------------------------------
-- 5. VERIFICATION
-- ---------------------------------------------------------------------
select jobname, schedule, active from cron.job order by jobname;
